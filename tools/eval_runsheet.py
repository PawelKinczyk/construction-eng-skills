#!/usr/bin/env python3
"""Build the prompt run sheet for checking skill behaviour, from the skills' own evals.

Reads every skills/<name>/evals/evals.json and writes tools/eval-checklist.md: one prompt per
case, verbatim, with the expected behaviour, the files the case needs, and a result table to
fill in after a run. Because it is generated from the evals, the sheet cannot drift away from
them: regenerate it after changing an eval.

Usage:
  python tools/eval_runsheet.py                      write tools/eval-checklist.md
  python tools/eval_runsheet.py --skill punch-list    print one skill's prompts
  python tools/eval_runsheet.py --smoke               print only the first case of each skill
  python tools/eval_runsheet.py --since HEAD~1        list the skills whose files changed since
                                                      a git revision (needs git on PATH)

A run is judged by a person or by an agent, not by this script. The script only prepares the
sheet and says which prompts a change makes relevant.
"""

import argparse
import json
import subprocess
import sys
from datetime import date
from pathlib import Path

# Windows consoles default to a legacy code page and cannot print Polish or unit symbols.
for stream in (sys.stdout, sys.stderr):
    if hasattr(stream, "reconfigure"):
        stream.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
OUT = ROOT / "tools" / "eval-checklist.md"

RUBRIC = """
Judge each run against these, in this order:

| # | Check | Fail example |
|---|---|---|
| 1 | Uses the skill's procedure, not a generic answer | answers from general knowledge without loading the discipline or jurisdiction file |
| 2 | Uses the scripts for the arithmetic | calculates a flow or a rollup in its head |
| 3 | No invented values | quotes a clause number, a unit rate or a model that was never supplied |
| 4 | Marks unknowns to verify | fills a missing value with a plausible guess |
| 5 | Right deliverable language | answers in English when `PROJECT.md` sets Polish |
| 6 | Right output format | free prose where the skill defines a table or a section order |
| 7 | Routes to the other skill | prices equipment in `code-compliance`, or writes a notice in `site-visit` |
| 8 | States its limits | presents a check as an approval, a drawing register as a survey, a model count as a quantity |

Result values: `pass`, `pass with notes`, `fail`. A fail is a defect in the skill, in its
references or in its scripts; record it as an issue before changing anything else.
"""


def skill_dirs():
    return sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").exists())


def load_cases(skill):
    path = skill / "evals" / "evals.json"
    if not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    return data.get("evals", [])


def changed_skills(revision):
    """Skills whose files changed since a git revision, mapped from the changed paths."""
    try:
        result = subprocess.run(["git", "diff", "--name-only", revision, "--", "skills", "shared"],
                                cwd=ROOT, capture_output=True, text=True, check=True)
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        print(f"ERROR: cannot read git history ({exc})", file=sys.stderr)
        return None
    names = set()
    for line in result.stdout.splitlines():
        parts = Path(line).parts
        if len(parts) >= 2 and parts[0] == "skills":
            names.add(parts[1])
        elif parts and parts[0] == "shared":
            names.update(s.name for s in skill_dirs())
    return names


def print_prompts(skills, smoke=False):
    for skill in skills:
        cases = load_cases(skill)
        if smoke:
            cases = cases[:1]
        if not cases:
            continue
        print(f"\n=== {skill.name} ===")
        for case in cases:
            print(f"\n[{skill.name} #{case.get('id')}]")
            print(f"prompt: {case.get('prompt')}")
            print(f"expect: {case.get('expected_output')}")
            if case.get("files"):
                print(f"files:  {', '.join(case['files'])}")


def write_checklist(skills):
    lines = [
        "# Skill prompt checklist",
        "",
        "Generated by `python tools/eval_runsheet.py`. Do not edit by hand: change the skill's",
        "`evals/evals.json` and regenerate. Smoke prompts for quick checks are in",
        "[smoke-prompts.md](smoke-prompts.md).",
        "",
        f"Repository revision: {git_revision()}    Generated: {date.today().isoformat()}",
        "",
        "## How to run",
        "",
        "1. `python tools/build.py check` and `python tools/verify_skills.py`: structure first.",
        "2. Start a fresh conversation per skill, or at least per group, so a previous answer does",
        "   not prime the next one.",
        "3. Paste the prompt with the files listed for that case. Where the case needs a project,",
        "   use `skills/project-brief/examples/PROJECT.example.md`.",
        "4. Compare the answer with the expected behaviour, not word for word: the checks are the",
        "   rubric below.",
        "5. Record the result in the table of the skill, and any failure as an issue.",
        "",
        "## Rubric and result values",
        RUBRIC,
    ]
    for skill in skills:
        cases = load_cases(skill)
        if not cases:
            continue
        lines.append(f"\n## {skill.name}")
        lines.append("")
        lines.append("| # | Result | Notes (failure: what the skill did instead) |")
        lines.append("|---|---|---|")
        for case in cases:
            lines.append(f"| {case.get('id')} | | |")
        for case in cases:
            lines.append("")
            lines.append(f"### {skill.name} #{case.get('id')}")
            lines.append("")
            lines.append(f"**Prompt**")
            lines.append("")
            lines.append("```")
            lines.append(str(case.get("prompt", "")))
            lines.append("```")
            lines.append("")
            lines.append(f"**Expected behaviour**")
            lines.append("")
            lines.append(str(case.get("expected_output", "")))
            if case.get("files"):
                lines.append("")
                lines.append("**Files to provide**: " + ", ".join(case["files"]))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    total = sum(len(load_cases(s)) for s in skills)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(skills)} skill(s), {total} prompt(s)")
    return 0


def git_revision():
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def main():
    parser = argparse.ArgumentParser(description="Prompt run sheet for skill checks.")
    parser.add_argument("--skill", help="one skill only")
    parser.add_argument("--smoke", action="store_true", help="first case of each skill")
    parser.add_argument("--since", help="only skills changed since this git revision")
    parser.add_argument("--write", action="store_true",
                        help="write the full checklist even when a selector is given")
    args = parser.parse_args()

    skills = skill_dirs()
    if args.skill:
        skills = [s for s in skills if s.name == args.skill]
        if not skills:
            print(f"ERROR: no skill named {args.skill}", file=sys.stderr)
            return 2
    if args.since:
        names = changed_skills(args.since)
        if names is None:
            return 2
        if not names:
            print(f"no skill files changed since {args.since}")
            return 0
        skills = [s for s in skills if s.name in names]
        print(f"skills changed since {args.since}: " + ", ".join(s.name for s in skills))
    if not args.write and (args.smoke or args.skill or args.since):
        print_prompts(skills, smoke=args.smoke)
        return 0
    return write_checklist(skills)


if __name__ == "__main__":
    sys.exit(main())
