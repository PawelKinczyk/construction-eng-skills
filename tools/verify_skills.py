#!/usr/bin/env python3
"""Structural verification of the skills in this repository.

Checks what can be checked without an agent: files and paths exist, frontmatter is valid,
SKILL.md stays under the line limit, every path it mentions resolves, every script compiles,
imports only the standard library plus the declared optional dependencies, responds to --help,
and every skill has examples and at least three eval cases with valid fields.

It does NOT judge the content, the wording or the behaviour of a skill. Run the prompts in
tools/eval-checklist.md (generated by tools/eval_runsheet.py) for that.

Usage:
  python tools/verify_skills.py [--json] [--no-help] [--skill <name>]

Exit codes: 0 all checks passed, 1 errors found, 2 bad usage.
Warnings do not fail the run; errors do.
"""

import argparse
import ast
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
REQUIREMENTS = ROOT / "tools" / "requirements-optional.txt"
MAX_LINES = 500
MAX_DESCRIPTION = 1024
MIN_EVALS = 3
PATH_RE = re.compile(r"\b(?:references|scripts|examples|assets)/[A-Za-z0-9._/-]+")
PATH_TRAILING = ".,;:)"
SKILL_REF_RE = re.compile(r"`([a-z][a-z0-9-]+)`")


def read_frontmatter(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    data, key = {}, None
    for line in lines[1:]:
        if line.strip() == "---":
            return data
        if line[:1] in (" ", "\t") and key:
            data[key] = (data[key] + " " + line.strip()).strip()
            continue
        if ":" in line:
            key, value = line.split(":", 1)
            data[key.strip()] = value.strip().strip("\"'")
    return None


def optional_dependencies():
    names = set()
    if REQUIREMENTS.exists():
        for line in REQUIREMENTS.read_text(encoding="utf-8").splitlines():
            line = line.split("#")[0].strip()
            if not line:
                continue
            name = re.split(r"[<>=!\[]", line)[0].strip()
            if name:
                names.add(name.lower().replace("-", "_"))
    return names


def skill_dirs():
    return sorted(p for p in SKILLS.iterdir() if p.is_dir() and (p / "SKILL.md").exists())


def find_mentioned_paths(text):
    """Paths mentioned in a SKILL.md, stripped of trailing punctuation."""
    found = set()
    for match in PATH_RE.finditer(text):
        candidate = match.group(0).rstrip(PATH_TRAILING)
        found.add(candidate)
    return found


def check_references(skill, errors, warnings):
    """Paths in SKILL.md, and cross-skill references, must resolve."""
    text = (skill / "SKILL.md").read_text(encoding="utf-8")
    mentioned = find_mentioned_paths(text)
    for rel in sorted(mentioned):
        target = skill / rel
        if target.exists():
            continue
        # a path into another skill's folder is written as <skill>/references/...
        if rel.startswith("references/shared/") and (ROOT / "shared" / rel[len("references/shared/"):]).exists():
            continue
        if (ROOT / rel).exists():
            continue
        errors.append(f"{skill.name}: SKILL.md mentions '{rel}' which does not exist")
    scripts = sorted(p.name for p in (skill / "scripts").glob("*.py")) if (skill / "scripts").exists() else []
    for script in scripts:
        if script not in text:
            warnings.append(f"{skill.name}: script '{script}' is not mentioned in SKILL.md")
    for script in re.findall(r"scripts/([A-Za-z0-9_.]+\.py)", text):
        if scripts and script not in scripts:
            errors.append(f"{skill.name}: SKILL.md mentions script '{script}' which is not in scripts/")
    for other in SKILL_REF_RE.findall(text):
        if other in {s.name for s in skill_dirs()} or other in ("tools", "shared", "templates"):
            continue


def check_scripts(skill, errors, warnings, check_help=True):
    scripts_dir = skill / "scripts"
    if not scripts_dir.exists():
        return
    allowed = optional_dependencies() | {m.lower().replace("-", "_") for m in sys.stdlib_module_names}
    for script in sorted(scripts_dir.glob("*.py")):
        source = script.read_text(encoding="utf-8")
        try:
            tree = ast.parse(source)
        except SyntaxError as exc:
            errors.append(f"{skill.name}/{script.name}: syntax error: {exc}")
            continue
        imported = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.update(alias.name.split(".")[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
                imported.add(node.module.split(".")[0])
        for module in sorted(imported):
            key = module.lower().replace("-", "_")
            if key not in allowed:
                errors.append(f"{skill.name}/{script.name}: imports '{module}', which is neither "
                              "standard library nor declared in tools/requirements-optional.txt")
        if "'__main__'" not in source and '"__main__"' not in source:
            warnings.append(f"{skill.name}/{script.name}: no __main__ guard")
        if '"--json"' not in source and "'--json'" not in source and '"json"' not in source:
            warnings.append(f"{skill.name}/{script.name}: no JSON output option (--json or "
                            "--format json)")
        if check_help:
            result = subprocess.run([sys.executable, str(script), "--help"],
                                    capture_output=True, text=True, timeout=60)
            if result.returncode != 0:
                errors.append(f"{skill.name}/{script.name}: --help failed with code "
                              f"{result.returncode}: {result.stderr.strip().splitlines()[:1]}")


def check_evals(skill, errors, warnings):
    path = skill / "evals" / "evals.json"
    if not path.exists():
        errors.append(f"{skill.name}: no evals/evals.json")
        return 0
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        errors.append(f"{skill.name}: evals.json is not valid JSON: {exc}")
        return 0
    cases = data.get("evals", [])
    if data.get("skill_name") != skill.name:
        errors.append(f"{skill.name}: evals.json skill_name is {data.get('skill_name')!r}")
    if len(cases) < MIN_EVALS:
        errors.append(f"{skill.name}: {len(cases)} eval case(s), minimum is {MIN_EVALS}")
    ids = []
    for case in cases:
        for field in ("id", "prompt", "expected_output"):
            if not case.get(field):
                errors.append(f"{skill.name}: eval {case.get('id', '?')} has no {field}")
        ids.append(case.get("id"))
        for rel in case.get("files", []):
            target = (skill / rel).resolve()
            if not target.exists():
                errors.append(f"{skill.name}: eval {case.get('id')} file '{rel}' does not exist")
        if len(case.get("expected_output", "")) < 80:
            warnings.append(f"{skill.name}: eval {case.get('id')} expected_output is thin "
                            "(under 80 characters); it cannot be judged against")
    if len(set(ids)) != len(ids):
        errors.append(f"{skill.name}: duplicate eval ids")
    return len(cases)


def check_examples(skill, errors, warnings):
    examples = skill / "examples"
    if not examples.exists() or not any(examples.iterdir()):
        errors.append(f"{skill.name}: no examples")
    else:
        for path in sorted(examples.iterdir()):
            if path.is_file() and path.suffix in (".md", ".json"):
                text = path.read_text(encoding="utf-8")
                if not text.strip():
                    errors.append(f"{skill.name}: empty example {path.name}")
                if path.suffix == ".md" and "example" not in text.lower() and "przykład" not in text.lower():
                    warnings.append(f"{skill.name}: {path.name} does not say it is an example")


def check_skill(skill, check_help=True):
    errors, warnings = [], []
    skill_md = skill / "SKILL.md"
    text = skill_md.read_text(encoding="utf-8")
    lines = len(text.splitlines())
    if lines > MAX_LINES:
        errors.append(f"{skill.name}: SKILL.md has {lines} lines, max {MAX_LINES}")
    frontmatter = read_frontmatter(skill_md)
    if frontmatter is None:
        errors.append(f"{skill.name}: SKILL.md has no closed frontmatter block")
    else:
        name = frontmatter.get("name", "")
        description = frontmatter.get("description", "")
        if name != skill.name:
            errors.append(f"{skill.name}: frontmatter name {name!r} does not match the folder")
        if not description:
            errors.append(f"{skill.name}: frontmatter has no description")
        elif len(description) > MAX_DESCRIPTION:
            errors.append(f"{skill.name}: description is {len(description)} characters, "
                          f"max {MAX_DESCRIPTION}")
        elif len(description) < 120:
            warnings.append(f"{skill.name}: description is short ({len(description)} characters); "
                            "the agent picks the skill from this text alone")
    for heading in ("## 1. Load context", "## 3. Work", "## 4. Verify", "## 5. Output"):
        if heading not in text:
            errors.append(f"{skill.name}: SKILL.md has no '{heading}' section")
    verify_words = ("to verify", "to confirm", "to be confirmed", "open question",
                    "do weryfikacji", "to weryfikacji", "unverified")
    if not any(word in text.lower() for word in verify_words):
        warnings.append(f"{skill.name}: SKILL.md never marks anything as needing confirmation")
    check_references(skill, errors, warnings)
    check_scripts(skill, errors, warnings, check_help)
    evals = check_evals(skill, errors, warnings)
    check_examples(skill, errors, warnings)
    return {"skill": skill.name, "errors": errors, "warnings": warnings,
            "lines": lines, "evals": evals}


def main():
    parser = argparse.ArgumentParser(description="Structural verification of the skills.")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--no-help", action="store_true",
                        help="skip running each script with --help")
    parser.add_argument("--skill", help="check one skill only")
    args = parser.parse_args()

    skills = skill_dirs()
    if args.skill:
        skills = [s for s in skills if s.name == args.skill]
        if not skills:
            print(f"ERROR: no skill named {args.skill}", file=sys.stderr)
            return 2

    results = [check_skill(skill, check_help=not args.no_help) for skill in skills]
    errors = [e for r in results for e in r["errors"]]
    warnings = [w for r in results for w in r["warnings"]]

    if args.json:
        print(json.dumps({"skills": results, "errors": len(errors), "warnings": len(warnings)},
                         ensure_ascii=False, indent=2))
        return 1 if errors else 0

    for result in results:
        state = "ERROR" if result["errors"] else ("warn" if result["warnings"] else "ok")
        print(f"[{state:<5}] {result['skill']:<22} {result['lines']:>4} lines, "
              f"{result['evals']} evals")
    if warnings:
        print("\nWarnings:")
        for warning in warnings:
            print(f"  - {warning}")
    if errors:
        print("\nErrors:")
        for error in errors:
            print(f"  - {error}")
        print(f"\n{len(errors)} error(s), {len(warnings)} warning(s) in {len(results)} skill(s).")
        return 1
    print(f"\nOK: {len(results)} skill(s), {len(warnings)} warning(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
